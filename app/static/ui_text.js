const locales = Object.freeze({ en: english, es: spanish, ht: creole });
const savedLocale = window.localStorage?.getItem("ccw-locale");
let locale = Object.hasOwn(locales, savedLocale) ? savedLocale : "en";
const activeText = {};

function applyLocale(nextLocale, notify = true) {
  locale = Object.hasOwn(locales, nextLocale) ? nextLocale : "en";
  for (const key of Object.keys(activeText)) delete activeText[key];
  Object.assign(activeText, locales[locale]);
  if (typeof document !== "undefined") document.documentElement.lang = locale;
  window.localStorage?.setItem("ccw-locale", locale);
  if (notify && typeof window.dispatchEvent === "function") {
    window.dispatchEvent(new CustomEvent("ccw:localechange", { detail: { locale } }));
  }
}

function localizeControl(control) {
  if (!control) return;
  control.innerHTML = `<option value="en">${activeText.englishShort}</option><option value="es">${activeText.spanishShort}</option><option value="ht">${activeText.creoleShort}</option>`;
  control.value = locale;
  control.setAttribute("aria-label", activeText.language);
  control.setAttribute("title", activeText.language);
}

function bindControl(control) {
  if (!control || control.dataset.localeBound) return;
  control.dataset.localeBound = "true";
  localizeControl(control);
  control.addEventListener("change", () => applyLocale(control.value));
  window.addEventListener("ccw:localechange", () => localizeControl(control));
}

function translateContent(value) {
  const source = String(value ?? "").trim();
  if (locale === "en" || !source) return source;
  const direct = contentTranslations[locale]?.[source];
  if (direct) return direct;
  const fixed = source.match(/^(.+) was fixed at the clinic today\.$/);
  if (fixed) return activeText.historyFixedAtClinic.replace("{cat}", fixed[1]);
  return source;
}

applyLocale(locale, false);
window.UI_TEXTS = locales;
window.UI_TEXT = activeText;
window.UI_I18N = Object.freeze({
  get locale() { return locale; },
  setLocale: applyLocale,
  bindControl,
  localizeControl,
  translateContent,
});
